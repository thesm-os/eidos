// TestIsSentinelName pins the matcher half of [golang.SentinelName].
//
// The pair has to agree: a generator composing a name with one rule
// and finding it with another emits variables its own detector cannot
// see, and nothing fails until a consumer notices the sentinel it
// declared was ignored.
func TestIsSentinelName(t *testing.T) {
	t.Parallel()

	t.Run("matches what SentinelName composes", func(t *testing.T) {
		t.Parallel()
		for _, subject := range []string{"NotFound", "conflict", "Timeout"} {
			if got := golang.SentinelName(subject); !golang.IsSentinelName(got) {
				t.Errorf("SentinelName(%q) = %q, which IsSentinelName rejects", subject, got)
			}
		}
	})

	t.Run("Err alone is not a sentinel name", func(t *testing.T) {
		t.Parallel()
		// It carries the prefix and no subject, so it names nothing in
		// particular; admitting it would classify a package's generic
		// error variable as a sentinel for a type.
		if golang.IsSentinelName("Err") {
			t.Errorf("bare Err must not match")
		}
	})

	t.Run("rejects names that are not sentinels", func(t *testing.T) {
		t.Parallel()
		for _, ident := range []string{"", "NotFound", "errNotFound", "Errors", "Erro"} {
			if golang.IsSentinelName(ident) {
				t.Errorf("IsSentinelName(%q) = true, want false", ident)
			}
		}
	})
}

// TestSentinelSubject pins the third side of a pair that was two, and
// the round trip that makes the three one rule.
func TestSentinelSubject(t *testing.T) {
	t.Parallel()

	t.Run("strips the prefix from a sentinel", func(t *testing.T) {
		t.Parallel()
		subject, prefixed := golang.SentinelSubject("ErrNotFound")
		if !prefixed || subject != "NotFound" {
			t.Fatalf("SentinelSubject = %q, %v; want NotFound, true", subject, prefixed)
		}
	})

	t.Run("round-trips against SentinelName", func(t *testing.T) {
		t.Parallel()
		// The property the three symbols exist to hold. Composed by one
		// rule and decomposed by another, a generator emits variables
		// its own detector cannot see.
		for _, subject := range []string{"gone", "NotFound", "url_path", "Conflict"} {
			name := golang.SentinelName(subject)
			back, prefixed := golang.SentinelSubject(name)
			if !prefixed || golang.SentinelName(back) != name {
				t.Fatalf("SentinelName(%q) = %q, back to %q (%v) — round trip broken",
					subject, name, back, prefixed)
			}
		}
	})

	t.Run("a name that merely starts with Err is returned whole", func(t *testing.T) {
		t.Parallel()
		// TrimPrefix turns Errors into ors, which is a valid identifier
		// and therefore compiles — with a subject the author never
		// wrote in every message that interpolates it.
		subject, prefixed := golang.SentinelSubject("Errors")
		if prefixed || subject != "Errors" {
			t.Fatalf("SentinelSubject(Errors) = %q, %v; want Errors, false", subject, prefixed)
		}
	})

	t.Run("bare Err carries no subject", func(t *testing.T) {
		t.Parallel()
		// TrimPrefix yields the empty string here, which renders as
		// nothing at all wherever the subject is interpolated.
		subject, prefixed := golang.SentinelSubject("Err")
		if prefixed || subject != "Err" {
			t.Fatalf("SentinelSubject(Err) = %q, %v; want Err, false", subject, prefixed)
		}
	})

	t.Run("an unexported error variable is not a sentinel", func(t *testing.T) {
		t.Parallel()
		// SentinelName cannot compose one, so reporting a subject for
		// it would claim a round trip that does not hold.
		subject, prefixed := golang.SentinelSubject("errNotFound")
		if prefixed || subject != "errNotFound" {
			t.Fatalf("SentinelSubject(errNotFound) = %q, %v; want it returned whole", subject, prefixed)
		}
	})

	t.Run("agrees with IsSentinelName on every input", func(t *testing.T) {
		t.Parallel()
		// One rule, three symbols. A disagreement here is a name one
		// half classifies as a sentinel and the other decomposes as
		// though it were not.
		for _, ident := range []string{"ErrNotFound", "Errors", "Err", "errNotFound", "", "Err_"} {
			_, prefixed := golang.SentinelSubject(ident)
			if prefixed != golang.IsSentinelName(ident) {
				t.Fatalf("SentinelSubject(%q) prefixed=%v but IsSentinelName=%v",
					ident, prefixed, golang.IsSentinelName(ident))
			}
		}
	})
}

// TestHasTagOption_Absent pins the miss. A tag that is present but
// carries a different option must read as absent, or a generator emits
// the behaviour the author spelled off.
func TestHasTagOption_Absent(t *testing.T) {
	t.Parallel()

	t.Run("an option the tag does not carry reads false", func(t *testing.T) {
		t.Parallel()
		f := &node.Field{Name: "ID", Type: builtinRef("string"), Tag: `json:"id,omitempty"`}
		if golang.HasTagOption(f, "json", "string") {
			t.Error("an option absent from the tag reported present")
		}
	})

	t.Run("an option the tag does carry still reads true", func(t *testing.T) {
		t.Parallel()
		f := &node.Field{Name: "ID", Type: builtinRef("string"), Tag: `json:"id,omitempty"`}
		if !golang.HasTagOption(f, "json", "omitempty") {
			t.Error("an option present in the tag reported absent")
		}
	})
}

// A docblock naming a derived identifier wraps after the substitution,
// not before it.
//
// The defect: a template wrapping its own prose has to guess the
// identifier's length while writing it, and the guess is wrong for
// every declaration of a different name. A builder for `Comment` left
// one line short and one at 86 columns, and gofmt rewraps neither.
func TestWrapDoc(t *testing.T) {
	t.Parallel()

	t.Run("no line exceeds the width", func(t *testing.T) {
		t.Parallel()
		got := golang.WrapDoc(
			"CommentBuilder constructs values. Every setter returns the " +
				"builder, so calls chain. A builder is a value under construction " +
				"and is not safe for concurrent use; [CommentBuilder.Clone] is how " +
				"one becomes two.",
		)
		for line := range strings.SplitSeq(got, "\n") {
			if len(line) > golang.DocWidth+len("// ") {
				t.Errorf("line is %d columns, want at most %d: %q",
					len(line), golang.DocWidth+3, line)
			}
		}
	})

	t.Run("every line carries the comment marker", func(t *testing.T) {
		t.Parallel()
		for line := range strings.SplitSeq(golang.WrapDoc("one two three"), "\n") {
			if !strings.HasPrefix(line, "//") {
				t.Errorf("line %q is not a comment; a template pasting this into "+
					"source would emit it as code", line)
			}
		}
	})

	t.Run("a blank line separates paragraphs", func(t *testing.T) {
		t.Parallel()
		// godoc reads a blank comment line as a paragraph break, so a
		// helper that dropped it would run a summary into its body and
		// leave the symbol with a four-sentence first line.
		got := golang.WrapDoc("First paragraph.\n\nSecond paragraph.")
		if !strings.Contains(got, "\n//\n") {
			t.Errorf("got %q, want the paragraphs separated by a bare marker", got)
		}
	})

	t.Run("an over-long word takes a line of its own", func(t *testing.T) {
		t.Parallel()
		// The words that reach that length here are identifiers and
		// import paths, and a broken one stops being a link godoc
		// resolves.
		long := strings.Repeat("x", golang.DocWidth+10)
		if got := golang.WrapDoc("see " + long); !strings.Contains(got, "// "+long) {
			t.Errorf("got %q, want the long word intact on its own line", got)
		}
	})

	t.Run("empty text renders nothing", func(t *testing.T) {
		t.Parallel()
		if got := golang.WrapDoc("   \n  "); got != "//" {
			t.Errorf("got %q; a symbol with nothing to say still needs a "+
				"well-formed comment rather than a bare prefix with a space", got)
		}
	})
}
