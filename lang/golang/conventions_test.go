func TestGeneratedHeader(t *testing.T) {
	t.Parallel()

	t.Run("renders the canonical marker", func(t *testing.T) {
		t.Parallel()
		got := golang.GeneratedHeader("eidos")
		if got != "// Code generated by eidos. DO NOT EDIT." {
			t.Fatalf("GeneratedHeader = %q", got)
		}
	})

	t.Run("the header it writes is the header it recognises", func(t *testing.T) {
		t.Parallel()
		// The round trip is the whole contract: a header that differs
		// in spacing or punctuation is not a generated-file marker to
		// gopls, to the lint `generated` filter, or to coverage — the
		// file is treated as hand-written and its findings reach an
		// author who cannot act on them.
		if !golang.IsGeneratedSource(golang.GeneratedHeader("testkit")) {
			t.Fatalf("GeneratedHeader must satisfy IsGeneratedSource")
		}
	})

	t.Run("a near-miss is not a marker", func(t *testing.T) {
		t.Parallel()
		for _, line := range []string{
			"// Code generated by eidos. DO NOT EDIT",  // no full stop
			"// code generated by eidos. DO NOT EDIT.", // lower case
			"//Code generated by eidos. DO NOT EDIT.",  // no space
			"// Generated by eidos. DO NOT EDIT.",      // wrong opening
			"  // Code generated by x. DO NOT EDIT.",   // indented
		} {
			if golang.IsGeneratedSource(line) {
				t.Errorf("IsGeneratedSource(%q) = true", line)
			}
		}
	})

	t.Run("tolerates a trailing newline", func(t *testing.T) {
		t.Parallel()
		// Callers scan a file's leading lines, which carry theirs.
		if !golang.IsGeneratedSource(golang.GeneratedHeader("x") + "\n") {
			t.Fatalf("a trailing newline must not defeat the match")
		}
	})

	t.Run("an unnamed tool still produces a valid marker", func(t *testing.T) {
		t.Parallel()
		if !golang.IsGeneratedSource(golang.GeneratedHeader("")) {
			t.Fatalf("an empty tool name must still yield a valid marker")
		}
	})
}

