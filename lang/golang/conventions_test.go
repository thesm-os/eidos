func TestDocDeprecation(t *testing.T) {
	t.Parallel()

	t.Run("reads the reason off the marker line", func(t *testing.T) {
		t.Parallel()
		reason, dep := golang.DocDeprecation("Get returns the value.\n\nDeprecated: use Fetch.")
		if !dep || reason != "use Fetch." {
			t.Fatalf("DocDeprecation = %q, %v", reason, dep)
		}
	})

	t.Run("a mention in prose is not a marker", func(t *testing.T) {
		t.Parallel()
		// Treating it as one would report every comment explaining why
		// something is not deprecated.
		_, dep := golang.DocDeprecation("This is not Deprecated: it is current.")
		if dep {
			t.Fatalf("a mid-line mention must not read as a marker")
		}
	})

	t.Run("a comment with no marker reports none", func(t *testing.T) {
		t.Parallel()
		if _, dep := golang.DocDeprecation("Get returns the value."); dep {
			t.Fatalf("DocDeprecation found a marker where none is written")
		}
	})

	t.Run("what DeprecatedDoc writes, DocDeprecation reads", func(t *testing.T) {
		t.Parallel()
		reason, dep := golang.DocDeprecation(golang.DeprecatedDoc("use Fetch."))
		if !dep || reason != "use Fetch." {
			t.Fatalf("round trip = %q, %v", reason, dep)
		}
	})
}

