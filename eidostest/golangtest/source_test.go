func TestParse(t *testing.T) {
	t.Parallel()

	t.Run("reads a well-formed file", func(t *testing.T) {
		t.Parallel()
		if got := parse(t).Path(); got != "store_stub.gen.go" {
			t.Fatalf("Path = %q", got)
		}
	})

	t.Run("keeps the bytes it was given", func(t *testing.T) {
		t.Parallel()
		if string(parse(t).Bytes()) != primary {
			t.Fatalf("Bytes did not round-trip")
		}
	})
}

func TestPackageAndImports(t *testing.T) {
	t.Parallel()

	t.Run("reports the declared package", func(t *testing.T) {
		t.Parallel()
		parse(t).AssertPackage(t, "storepkg")
	})

	t.Run("lists every import", func(t *testing.T) {
		t.Parallel()
		parse(t).AssertImports(t, "context", "io").AssertNoImport(t, "reflect")
	})

	t.Run("pins the whole import set", func(t *testing.T) {
		t.Parallel()
		// A generator's imports are API: one added silently breaks every
		// consumer whose module does not already require it.
		parse(t).AssertImportsOnly(t, "io", "context")
	})

	t.Run("names what is unexpected and what is absent", func(t *testing.T) {
		t.Parallel()
		s := probe(t)
		parse(t).AssertImportsOnly(s, "context", "reflect")
		if !s.failed {
			t.Fatal("AssertImportsOnly accepted the wrong set")
		}
		for _, want := range []string{"unexpected: [io]", "absent: [reflect]"} {
			if !strings.Contains(s.msg, want) {
				t.Fatalf("message %q does not carry %q", s.msg, want)
			}
		}
	})
}

func TestGeneratedHeader(t *testing.T) {
	t.Parallel()

	t.Run("accepts the conventional line", func(t *testing.T) {
		t.Parallel()
		parse(t).AssertGeneratedHeader(t)
	})

	t.Run("rejects a header that drifted", func(t *testing.T) {
		t.Parallel()
		// Tooling keys off the exact spelling, so a near-miss opts every
		// consumer's output back into linting and review.
		drifted := strings.Replace(primary, "DO NOT EDIT.", "do not edit.", 1)
		s := probe(t)
		golangtest.Parse(t, golangtest.File{Path: "x.go", Src: []byte(drifted)}).
			AssertGeneratedHeader(s)
		if !s.failed {
			t.Fatal("AssertGeneratedHeader accepted a drifted header")
		}
	})
}

