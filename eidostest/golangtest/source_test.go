func TestGolden(t *testing.T) {
	t.Parallel()

	// withCommand is the header the backend stamps the invocation into,
	// which under `go test` is a temp binary path differing every run.
	withCommand := func(cmd string) *golangtest.Source {
		t.Helper()
		src := "// Code generated by eidos. DO NOT EDIT.\n//\n// Command:   " + cmd +
			"\n\npackage storepkg\n"
		return golangtest.Parse(t, golangtest.File{Path: "x.gen.go", Src: []byte(src)})
	}

	t.Run("normalises the volatile header line", func(t *testing.T) {
		t.Parallel()
		// Every generator keeping a golden had already written this
		// privately, and identically.
		got := string(withCommand("/tmp/go-build123/b001/x.test -test.v").Normalised())
		if !strings.Contains(got, golangtest.CommandPlaceholder) {
			t.Fatalf("Normalised did not rewrite the command line:\n%s", got)
		}
		if strings.Contains(got, "go-build123") {
			t.Fatalf("Normalised kept the volatile path:\n%s", got)
		}
	})

	t.Run("leaves a file with no command line alone", func(t *testing.T) {
		t.Parallel()
		if string(parse(t).Normalised()) != primary {
			t.Fatal("Normalised changed a file carrying no command line")
		}
	})

	t.Run("writes a golden that does not exist yet", func(t *testing.T) {
		t.Parallel()
		path := filepath.Join(t.TempDir(), "nested", "x.golden")
		withCommand("a").AssertGolden(t, path)
		written, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("the golden was not written: %v", err)
		}
		if !strings.Contains(string(written), golangtest.CommandPlaceholder) {
			t.Fatal("the golden holds the volatile line")
		}
	})

	t.Run("accepts two runs whose invocations differed", func(t *testing.T) {
		t.Parallel()
		// The whole point: the golden is about the generated code rather
		// than about how the suite was invoked.
		path := filepath.Join(t.TempDir(), "x.golden")
		withCommand("/tmp/first.test").AssertGolden(t, path)
		withCommand("/tmp/second.test -run X").AssertGolden(t, path)
	})

	t.Run("reports a file that moved", func(t *testing.T) {
		t.Parallel()
		path := filepath.Join(t.TempDir(), "x.golden")
		withCommand("a").AssertGolden(t, path)
		s := probe(t)
		golangtest.Parse(t, golangtest.File{
			Path: "x.gen.go", Src: []byte("package other\n"),
		}).AssertGolden(s, path)
		if !s.failed {
			t.Fatal("AssertGolden accepted a file that moved")
		}
	})
}

func TestDocumented(t *testing.T) {
	t.Parallel()

	t.Run("accepts fully documented output", func(t *testing.T) {
		t.Parallel()
		golangtest.Parse(t, golangtest.File{
			Path: "x.go", Src: []byte(
				"package x\n\n// T is documented.\ntype T struct{}\n\n" +
					"// F is documented.\nfunc F() {}\n\n" +
					"// M is documented.\nfunc (t T) M() {}\n\n" +
					"// Sentinels.\nvar (\n\tErrA error\n\tErrB error\n)\n" +
					"func unexported() {}\n",
			),
		}).AssertDocumented(t)
	})

	t.Run("names every exported declaration carrying no comment", func(t *testing.T) {
		t.Parallel()
		// A consumer whose linter requires comments on exported
		// declarations gets those failures from generated code, and
		// blames themselves.
		s := probe(t)
		golangtest.Parse(t, golangtest.File{
			Path: "x.go", Src: []byte(
				"package x\n\ntype T struct{}\n\nfunc F() {}\n\nfunc (t T) M() {}\n\nvar Err error\n",
			),
		}).AssertDocumented(s)
		if !s.failed {
			t.Fatal("AssertDocumented accepted undocumented API")
		}
		for _, want := range []string{"Err", "F", "T", "T.M"} {
			if !strings.Contains(s.msg, want) {
				t.Fatalf("message %q does not name %q", s.msg, want)
			}
		}
	})

	t.Run("ignores what a consumer cannot name", func(t *testing.T) {
		t.Parallel()
		golangtest.Parse(t, golangtest.File{
			Path: "x.go", Src: []byte(
				"package x\n\ntype hidden struct{}\n\nfunc (h hidden) M() {}\n\nvar unexported int\n",
			),
		}).AssertDocumented(t)
	})
}
