func TestOrder(t *testing.T) {
	t.Parallel()

	t.Run("accepts a declaration that comes first", func(t *testing.T) {
		t.Parallel()
		parse(t).AssertOrder(t, "StoreGetStub", "StoreStub")
	})

	t.Run("rejects one that comes second", func(t *testing.T) {
		t.Parallel()
		// A contribution rendered ahead of the type it hangs off still
		// compiles; only a reader notices.
		s := probe(t)
		parse(t).AssertOrder(s, "StoreStub", "StoreGetStub")
		if !s.failed || !strings.Contains(s.msg, "after") {
			t.Fatalf("AssertOrder = %v, %q", s.failed, s.msg)
		}
	})

	t.Run("names what the file does declare", func(t *testing.T) {
		t.Parallel()
		s := probe(t)
		parse(t).AssertOrder(s, "Absent", "StoreStub")
		if !s.failed || !strings.Contains(s.msg, "StoreGetStub") {
			t.Fatalf("message %q does not list the declarations", s.msg)
		}
	})
}

