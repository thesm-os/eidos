// seedDeletedSourceFile writes a generated file at dir/name whose
// owning source package lives at an import path with no directory
// under the module — the on-disk shape left behind when someone
// deletes a source package.
//
// A go.mod is written at the workdir so goneSources can resolve
// import paths to directories at all; without one it declines to
// classify anything.
func seedDeletedSourceFile(
	t *testing.T, workdir, brand, dir, name string,
) (path string, target emit.Target) {
	t.Helper()
	modBody := "module example.com/m\n\ngo 1.26\n"
	if err := os.WriteFile(filepath.Join(workdir, "go.mod"), []byte(modBody), 0o600); err != nil {
		t.Fatalf("write go.mod: %v", err)
	}
	if err := os.MkdirAll(filepath.Join(workdir, dir), 0o750); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	body := []byte("// Code generated by " + brand + ". DO NOT EDIT.\npackage x\n")
	path = filepath.Join(workdir, dir, name)
	if err := os.WriteFile(path, body, 0o600); err != nil {
		t.Fatalf("write fixture: %v", err)
	}
	// example.com/m/gone is deliberately never created on disk and
	// never registered by the frontend: out of scope AND absent.
	return path, emit.Target{
		Dir: dir, Filename: name, Package: "x", ImportPath: "example.com/m/gone",
	}
}

// TestPruneCommand_DeletedSources covers the orphan class Scope
// cannot decide: an output whose source package was deleted.
//
// Deleting a source package is the act that strands an output, and it
// is the one case the scope guard is blind to — the package cannot be
// loaded, so it is indistinguishable from one a narrow run was never
// asked to examine. The flag is what separates them, so both of its
// positions are pinned here.
func TestPruneCommand_DeletedSources(t *testing.T) {
	t.Parallel()

	setup := func(t *testing.T) (*cli.Env, *bytes.Buffer, string, []plugin.Plugin) {
		t.Helper()
		env, stdout, _ := freshEnv(t, "eidos")
		path, target := seedDeletedSourceFile(t, env.Workdir, env.Brand, "out", "orphan.go")
		plugins := []plugin.Plugin{
			stubFrontend{name: "fe"},
			stubBackend{name: "be", lang: "stub"},
		}
		writePrevManifest(t, env, derivePruneTestPipelineID(t, env, plugins), target)
		return env, stdout, path, plugins
	}

	t.Run("without the flag the orphan survives", func(t *testing.T) {
		t.Parallel()
		env, _, path, plugins := setup(t)
		cmd := &cli.PruneCommand{Config: cli.PruneConfig{Plugins: plugins}}
		if code := cmd.Execute(t.Context(), env); code != cli.ExitOK {
			t.Fatalf("Execute = %d, want ExitOK", code)
		}
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("default prune must not act on inference; stat err=%v", err)
		}
	})

	t.Run("with the flag the orphan is deleted", func(t *testing.T) {
		t.Parallel()
		env, stdout, path, plugins := setup(t)
		cmd := &cli.PruneCommand{Config: cli.PruneConfig{
			Plugins: plugins, DeletedSources: true,
		}}
		if code := cmd.Execute(t.Context(), env); code != cli.ExitOK {
			t.Fatalf("Execute = %d, want ExitOK", code)
		}
		if _, err := os.Stat(path); !errors.Is(err, os.ErrNotExist) {
			t.Fatalf("orphan should be deleted; stat err=%v", err)
		}
		if !strings.Contains(stdout.String(), "deleted:") {
			t.Fatalf("expected deletion line; got %q", stdout.String())
		}
	})

	t.Run("dry run with the flag reports without deleting", func(t *testing.T) {
		t.Parallel()
		env, stdout, path, plugins := setup(t)
		cmd := &cli.PruneCommand{Config: cli.PruneConfig{
			Plugins: plugins, DeletedSources: true, DryRun: true,
		}}
		if code := cmd.Execute(t.Context(), env); code != cli.ExitOK {
			t.Fatalf("Execute = %d, want ExitOK", code)
		}
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("dry run must not delete; stat err=%v", err)
		}
		if !strings.Contains(stdout.String(), "would delete:") {
			t.Fatalf("expected a would-delete line; got %q", stdout.String())
		}
	})

	t.Run("the flag is registered", func(t *testing.T) {
		t.Parallel()
		cmd := &cli.PruneCommand{}
		fs := flag.NewFlagSet("prune", flag.ContinueOnError)
		cmd.RegisterFlags(fs)
		if fs.Lookup(cli.FlagDeletedSources) == nil {
			t.Fatalf("%s must be registered", cli.FlagDeletedSources)
		}
	})
}
